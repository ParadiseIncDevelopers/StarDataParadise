def update_install_lists() -> None:
    """Keep explicit CMake and WiX file lists in sync with the rendered manifest."""
    manifest = json.loads((IMAGES / "ui/sdp-tabler-icons.json").read_text(encoding="utf-8"))
    names = sorted({Path(row["file"]).name for row in manifest["outputs"]
                    if row["file"].startswith("ui/") and
                    Path(row["file"]).name != "refresh_sidebar.png"})
    names.append("sdp-tabler-icons.json")

    def replace_block(path: Path, start: str, end: str, block: str, anchor: str) -> None:
        raw = path.read_bytes()
        newline = "\r\n" if b"\r\n" in raw else "\n"
        text = raw.decode("utf-8").replace("\r\n", "\n")
        if start in text:
            text = re.sub(re.escape(start) + r".*?" + re.escape(end),
                          lambda _: block, text, count=1, flags=re.S)
        else:
            if anchor not in text:
                raise ValueError(f"Install-list insertion anchor missing: {path}")
            text = text.replace(anchor, block + "\n" + anchor, 1)
        path.write_bytes(text.replace("\n", newline).encode("utf-8"))

    cmake_start = "# BEGIN GENERATED CLASSIC TABLER ICONS"
    cmake_end = "# END GENERATED CLASSIC TABLER ICONS"
    cmake = "\n".join([
        cmake_start,
        "# Generated by packaging/classic-workbench/Generate-WorkspaceIcons.py.",
        "list(APPEND IMAGE_FILES",
        *("    " + name for name in names),
        ")",
        "install(FILES tabler-source/LICENSE.txt",
        "        DESTINATION ${WB_PACKAGE_SHARED_DIR}/images RENAME sdp-tabler-license.txt)",
        cmake_end,
    ])
    replace_block(IMAGES / "ui/CMakeLists.txt", cmake_start, cmake_end, cmake,
                  "install(FILES ${IMAGE_FILES} DESTINATION ${WB_PACKAGE_SHARED_DIR}/images)")

    wix_path = ROOT / "classic-workbench/build/msi/source/mysql_workbench_fragment.xml"
    wix_start = "                    <!-- BEGIN GENERATED CLASSIC TABLER ICONS -->"
    wix_end = "                    <!-- END GENERATED CLASSIC TABLER ICONS -->"
    files = []
    for name in names:
        identifier = re.sub(r"[^a-zA-Z0-9_]", "_", Path(name).stem)
        files.append(f'                    <File Id="file_sdpui_{identifier}" Name="{name}" />')
    files.append('                    <File Id="file_sdpui_tabler_license" Name="sdp-tabler-license.txt" '
                 'Source="images\\ui\\tabler-source\\LICENSE.txt" />')
    wix = "\n".join([wix_start, *files, wix_end])
    raw = wix_path.read_bytes()
    newline = "\r\n" if b"\r\n" in raw else "\n"
    text = raw.decode("utf-8").replace("\r\n", "\n")
    component = re.search(r'(<Component\b[^>]*\bId="images_ui"[^>]*>)(.*?)(\s*</Component>)', text, re.S)
    if component is None:
        raise ValueError("WiX images_ui component missing")
    content = component.group(2)
    if wix_start in content:
        content = re.sub(re.escape(wix_start) + r".*?" + re.escape(wix_end),
                         lambda _: wix, content, count=1, flags=re.S)
    else:
        content = content.rstrip() + "\n" + wix + "\n"
    text = text[:component.start(2)] + content + text[component.end(2):]
    wix_path.write_bytes(text.replace("\n", newline).encode("utf-8"))

    # Sidebar icons retain the native grt/structs paths. Existing 1x entries keep
    # their original installer IDs; only missing 2x/state variants are appended.
    grt_files = sorted({row["file"][len("grt/"):] for row in manifest["outputs"]
                        if row["file"].startswith("grt/")})
    grt_cmake_path = IMAGES / "grt/CMakeLists.txt"
    grt_start = "# BEGIN GENERATED CLASSIC TABLER SIDEBAR ICONS"
    grt_end = "# END GENERATED CLASSIC TABLER SIDEBAR ICONS"
    grt_text = grt_cmake_path.read_text(encoding="utf-8")
    grt_existing = re.sub(re.escape(grt_start) + r".*?" + re.escape(grt_end),
                          "", grt_text, flags=re.S)
    existing_names = set(re.findall(r"(?m)^\s+(\S+\.png)\s*$", grt_existing))
    grt_cmake = "\n".join([
        grt_start,
        "# Generated by packaging/classic-workbench/Generate-WorkspaceIcons.py.",
        "list(APPEND IMAGE_FILES",
        *("    " + name for name in grt_files if name not in existing_names),
        ")",
        grt_end,
    ])
    replace_block(grt_cmake_path, grt_start, grt_end, grt_cmake,
                  "install(FILES ${IMAGE_FILES} DESTINATION ${WB_PACKAGE_SHARED_DIR}/images)")

    raw = wix_path.read_bytes()
    newline = "\r\n" if b"\r\n" in raw else "\n"
    text = raw.decode("utf-8").replace("\r\n", "\n")
    component = re.search(r'(<Component\b[^>]*\bId="images_grt_structs"[^>]*>)(.*?)(\s*</Component>)',
                          text, re.S)
    if component is None:
        raise ValueError("WiX images_grt_structs component missing")
    grt_wix_start = "                      <!-- BEGIN GENERATED CLASSIC TABLER SIDEBAR ICONS -->"
    grt_wix_end = "                      <!-- END GENERATED CLASSIC TABLER SIDEBAR ICONS -->"
    content = component.group(2)
    existing = re.sub(re.escape(grt_wix_start) + r".*?" + re.escape(grt_wix_end),
                      "", content, flags=re.S)
    existing_names = set(re.findall(r'\bName="([^"]+)"', existing))
    files = []
    for path in grt_files:
        name = Path(path).name
        if name not in existing_names:
            identifier = re.sub(r"[^a-zA-Z0-9_]", "_", Path(name).stem)
            files.append(f'                      <File Id="file_sdpgrt_{identifier}" Name="{name}" />')
    grt_wix = "\n".join([grt_wix_start, *files, grt_wix_end])
    if grt_wix_start in content:
        content = re.sub(re.escape(grt_wix_start) + r".*?" + re.escape(grt_wix_end),
                         lambda _: grt_wix, content, count=1, flags=re.S)
    else:
        content = content.rstrip() + "\n" + grt_wix + "\n"
    text = text[:component.start(2)] + content + text[component.end(2):]
    wix_path.write_bytes(text.replace("\n", newline).encode("utf-8"))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--download", action="store_true", help="Fetch pinned official sources")
    parser.add_argument("--install-lists-only", action="store_true",
                        help="Refresh CMake/WiX lists from the existing manifest without rendering")
    args = parser.parse_args()
    if args.install_lists_only:
        update_install_lists()
        print(json.dumps({"ok": True, "install_lists_updated": True}))
        return
    SOURCE.mkdir(parents=True, exist_ok=True)
    if args.download:
        for name in ICON_NAMES:
            if (SOURCE / f"{name}.svg").is_file():
                continue
            url = f"{UPSTREAM}/icons/outline/{name}.svg"
            with urllib.request.urlopen(url, timeout=30) as response:
                (SOURCE / f"{name}.svg").write_bytes(response.read())
        with urllib.request.urlopen(f"{UPSTREAM}/LICENSE", timeout=30) as response:
            (SOURCE / "LICENSE.txt").write_bytes(response.read())

    # The Workbench native build already supplies Cairo and its dependent DLLs.
    native_libraries = ROOT / "out/workbench8-deps/lib"
    dll_directory = os.add_dll_directory(str(native_libraries)) if os.name == "nt" else None
    os.environ["PATH"] = str(native_libraries) + os.pathsep + os.environ.get("PATH", "")
    import cairosvg

    outputs = []

    def render(name: str, destination: Path, color: str = "#102629") -> None:
        original = (SOURCE / f"{name}.svg").read_text(encoding="utf-8")
        svg = original.replace('stroke="currentColor"', f'stroke="{color}"')
        for scale in (1, 2):
            target = destination.with_name(destination.stem + ("@2x" if scale == 2 else "") + ".png")
            cairosvg.svg2png(bytestring=svg.encode("utf-8"), write_to=str(target),
                            output_width=16 * scale, output_height=16 * scale)
            outputs.append({"file": target.relative_to(IMAGES).as_posix(),
                            "sha256": hashlib.sha256(target.read_bytes()).hexdigest(),
                            "source": name, "color": color, "size": 16 * scale})

    for name in ICON_NAMES:
        render(name, IMAGES / "ui" / f"sdp_{name}.png")
    render("player-play", IMAGES / "ui/sdp_player-play-white.png", "#FFFFFF")
    render("check", IMAGES / "ui/sdp_check-white.png", "#FFFFFF")
    for destination, source in SIDE_ICONS.items():
        color = "#9A6600" if destination == "db.Column.pk.side" else "#102629"
        if destination in ("db.Schema.loading.side", "db.Column.fk.side"):
            color = "#098874"
        if destination == "db.View.broken.side":
            color = "#A13D2D"
        render(source, IMAGES / "grt/structs" / f"{destination}.16x16.png", color)
    render("refresh", IMAGES / "ui/refresh_sidebar.png")
    manifest = {"upstream": "https://github.com/tabler/tabler-icons", "commit": COMMIT,
                "license": "MIT", "source_directory": "ui/tabler-source",
                "renderer": "CairoSVG", "outputs": outputs,
                "sources": [{"file": f"ui/tabler-source/{name}.svg",
                             "sha256": hashlib.sha256((SOURCE / f"{name}.svg").read_bytes()).hexdigest()}
                            for name in ICON_NAMES]}
    (IMAGES / "ui/sdp-tabler-icons.json").write_text(
        json.dumps(manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    update_install_lists()
    print(json.dumps({"ok": True, "icons": len(ICON_NAMES), "png_files": len(outputs)}))
    if dll_directory is not None:
        dll_directory.close()


if __name__ == "__main__":
    main()
